#!/bin/bash
# Rebuild src/_connected.blimp. The Blimp backend splices a _connected.blimp
# only for the library being built, not for the libraries it imports, so a
# test library that calls sys or http needs their bodies in its own file.
# Run after changing sys/src/_connected.blimp or http/src/_connected.blimp.
set -eu
cd "$(dirname "$0")"
{
  echo "# GENERATED by regen.sh from parts/client.blimp + sys and http _connected.blimp. Do not edit."
  cat parts/client.blimp
  for lib in sys http; do
    echo
    echo "# ---- copied from $lib/src/_connected.blimp ----"
    cat "../$lib/src/_connected.blimp"
  done
} > src/_connected.blimp
