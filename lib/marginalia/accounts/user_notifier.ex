defmodule Marginalia.Accounts.UserNotifier do
  import Swoosh.Email

  alias Marginalia.Mailer

  # Delivers the email using the application mailer.
  defp deliver(recipient, subject, body) do
    email =
      new()
      |> to(recipient)
      |> from({"Marginalia", "contact@example.com"})
      |> subject(subject)
      |> text_body(body)

    with {:ok, _metadata} <- Mailer.deliver(email) do
      {:ok, email}
    end
  end
  @doc """
  Deliver instructions to update a user email.

  This is the only email the app sends. Login is password-only; this exists so
  changing the address on an account still has to be proven at the new one.
  """
  def deliver_update_email_instructions(user, url) do
    deliver(user.email, "Update email instructions", """

    ==============================

    Hi #{user.email},

    You can change your email by visiting the URL below:

    #{url}

    If you didn't request this change, please ignore this.

    ==============================
    """)
  end
end
